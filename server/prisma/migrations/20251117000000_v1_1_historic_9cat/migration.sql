         AND "stl" >= 0 AND "blk" >= 0 AND "fg3m" >= 0 AND "tov" >= 0
         AND "fgm" >= 0 AND "fga" >= "fgm" AND "ftm" >= 0 AND "fta" >= "ftm"
         AND "fgm" >= "fg3m");

-- The locked game is chosen once, at game creation, and can never be changed.
-- (Replaces the v1 function, which referred to the old player_id column.)
CREATE OR REPLACE FUNCTION "forbid_locked_game_change"() RETURNS trigger AS $$
BEGIN
  IF NEW."locked_game_log_id" IS DISTINCT FROM OLD."locked_game_log_id"
     OR NEW."player_season_id" IS DISTINCT FROM OLD."player_season_id"
     OR NEW."game_id" IS DISTINCT FROM OLD."game_id" THEN
    RAISE EXCEPTION 'locked game for player-season % in game % is immutable', OLD."player_season_id", OLD."game_id"
      USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

