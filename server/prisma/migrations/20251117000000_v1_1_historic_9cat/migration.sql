-- Game settings: 1-13 players per team, and enough players in the pool to fill both rosters.
ALTER TABLE "games" ADD CONSTRAINT "games_settings_valid"
  CHECK ("roster_size" BETWEEN 1 AND 13
         AND "pool_size" >= 2 * "roster_size"
         AND "pool_size" <= 200);

-- Pick numbers start at 1; the upper bound (2 * roster_size) is checked by a trigger.
ALTER TABLE "draft_picks" ADD CONSTRAINT "draft_picks_pick_number_positive"
  CHECK ("pick_number" >= 1);

CREATE FUNCTION "check_pick_within_roster"() RETURNS trigger AS $$
DECLARE
  max_pick INTEGER;
BEGIN
  SELECT 2 * "roster_size" INTO max_pick FROM "games" WHERE "id" = NEW."game_id";
  IF NEW."pick_number" > max_pick THEN
    RAISE EXCEPTION 'pick % is past the end of the draft for game % (% picks)', NEW."pick_number", NEW."game_id", max_pick
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "draft_picks_within_roster"
  BEFORE INSERT OR UPDATE ON "draft_picks"
  FOR EACH ROW EXECUTE FUNCTION "check_pick_within_roster"();

